import assert from 'node:assert/strict';
import { randomBytes, randomUUID } from 'node:crypto';
import { createClient } from '@supabase/supabase-js';
import { cli, localSql } from './local-client.mjs';

// Reads local CLI status in memory. Never reads .env.local or prints any key/token.
// Synthetic Auth records remain in this disposable project (audit retention is
// deliberate); there is no destructive cleanup/reset operation in this script.
let assertions = 0;
function check(value, message) { assert.ok(value, message); assertions++; }
function requireSuccess(result, message) {
  if (result.error) throw new Error(`${message}: ${result.error.message}`);
  return result.data;
}
try {
  const status = JSON.parse(cli(['status', '--output', 'json']));
  const endpoint = new URL(status.API_URL);
  check(['127.0.0.1','localhost','[::1]'].includes(endpoint.hostname) && endpoint.port === '54321', 'Refuse non-local API endpoint');
  check(Boolean(status.ANON_KEY && status.SERVICE_ROLE_KEY), 'Local keys must be available');
  const options = { auth: { persistSession: false, autoRefreshToken: false, detectSessionInUrl: false } };
  const admin = createClient(endpoint.href, status.SERVICE_ROLE_KEY, options);
  const anonymous = createClient(endpoint.href, status.ANON_KEY, options);
  const users = [];
  for (let index=0; index<2; index++) {
    const email = `onit-db-test-${randomUUID()}@example.test`;
    const password = randomBytes(32).toString('base64url');
    const created = requireSuccess(await admin.auth.admin.createUser({
      email, password, email_confirm: true, user_metadata: { display_name: `Synthetic API ${index}`, role: 'admin' },
    }), 'Create synthetic local Auth user');
    const client = createClient(endpoint.href, status.ANON_KEY, options);
    requireSuccess(await client.auth.signInWithPassword({email,password}), 'Sign in synthetic local user');
    const provisioned = await Promise.all([client.rpc('ensure_individual_customer'),client.rpc('ensure_individual_customer')]);
    const account = requireSuccess(provisioned[0], 'Provision own local customer');
    const repeated = requireSuccess(provisioned[1], 'Repeat concurrent local provisioning');
    check(account === repeated, 'HTTP provisioning is idempotent');
    users.push({client,account,id:created.user.id});
  }
  const [a,b] = users;
  const profiles = requireSuccess(await a.client.from('profiles').select('id'), 'Read own profile');
  check(profiles.length === 1 && profiles[0].id === a.id, 'Profile HTTP isolation');
  const other = requireSuccess(await a.client.from('customer_profiles').select('id').eq('id',b.account), 'Query other account');
  check(other.length === 0, 'Account HTTP isolation');
  const privilegeEdit = await a.client.from('profiles').update({status:'suspended'}).eq('id',a.id);
  check(Boolean(privilegeEdit.error), 'Protected profile column write denied');
  const tables = await a.client.schema('private').from('employee_profiles').select('*');
  check(Boolean(tables.error), 'Private schema not exposed over API');
  const denied = await a.client.rpc('prepare_customer_upload', {p_account_id:b.account,p_content_type:'application/pdf',p_byte_size:10});
  check(Boolean(denied.error), 'Cross-account upload RPC denied');
  const pdf = Buffer.from('%PDF-1.4\nsynthetic disposable test\n');
  const prepared = requireSuccess(await a.client.rpc('prepare_customer_upload', {
    p_account_id:a.account,p_content_type:'application/pdf',p_byte_size:pdf.length,
  }), 'Prepare owned upload');
  requireSuccess(await a.client.storage.from(prepared.bucket).upload(prepared.object_name,pdf,{contentType:'application/pdf',upsert:false}), 'Upload owned file');
  const pending = await a.client.storage.from(prepared.bucket).download(prepared.object_name);
  check(Boolean(pending.error), 'Pending file cannot be downloaded through Storage API');
  // Only UUID values generated by this database enter the fixed-container SQL.
  check(/^[0-9a-f-]{36}$/.test(prepared.document_id), 'Database document ID is a UUID');
  localSql(`update private.document_objects set scan_status='clean' where id='${prepared.document_id}'::uuid;`);
  const clean = await a.client.storage.from(prepared.bucket).download(prepared.object_name);
  check(!clean.error, 'Clean owned file downloadable through Storage API');
  const cross = await b.client.storage.from(prepared.bucket).download(prepared.object_name);
  check(Boolean(cross.error), 'Other customer cannot download clean file');
  const overwrite = await a.client.storage.from(prepared.bucket).upload(prepared.object_name,pdf,{contentType:'application/pdf',upsert:true});
  check(Boolean(overwrite.error), 'Storage overwrite denied');
  await a.client.storage.from(prepared.bucket).remove([prepared.object_name]);
  const retained = await a.client.storage.from(prepared.bucket).download(prepared.object_name);
  check(!retained.error, 'End-user deletion cannot remove retained file');
  const anonymousFile = await anonymous.storage.from(prepared.bucket).download(prepared.object_name);
  check(Boolean(anonymousFile.error), 'Anonymous cannot download private object');
  const anonymousAccounts = await anonymous.from('customer_profiles').select('id');
  check(Boolean(anonymousAccounts.error), 'Anonymous has no account-table access');
  console.log(`PASS local Supabase Auth/REST/Storage API: ${assertions} assertions. Synthetic fixtures retained only in the disposable local project.`);
} catch(error) {
  console.error('Local Supabase API verification failed:',error.message);
  process.exitCode=1;
}
